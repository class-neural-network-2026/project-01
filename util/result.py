"""Results of a trained VAE (provided: do not modify this file).

Two functions are used by the notebook:

    evaluate(model)
        measures the trained model with the testing data, the 5,000 images
        of `get_dataset("test")` in data.py:
            FID (Frechet inception distance) between 5,000 images generated
                by the model and the 5,000 test images
            reconstruction error of the 5,000 test images
        For both, lower is better.

    save(result, info)
        saves the two values in the file
            result/result_<student ID>_<name>.csv

Usage (with the `util` and `code` folders on sys.path):
    from myinfo import get_info
    from result import evaluate, save

    result = evaluate(model)            # model: the trained VAE
    save(result, get_info())

The FID is computed with the package `torcheval`:
    pip install torcheval torchvision
It uses the Inception-v3 network of torchvision, pretrained on ImageNet. Its
weights (about 100 MB) are downloaded the first time `evaluate` is called,
which requires an internet connection, and are then read from the cache
folder of PyTorch. `evaluate` takes seconds with a GPU, but can take more
than 10 minutes with a CPU.
"""

import csv
from pathlib import Path

import torch
from torcheval.metrics import FrechetInceptionDistance

from data import get_dataset

# <project root>/result, independent of the directory the notebook is run from
RESULT_DIR = Path(__file__).resolve().parent.parent / "result"

# Number of images processed at a time. It is kept small because the
# Inception-v3 network works on images enlarged to 299 x 299 pixels.
BATCH_SIZE = 50

# Seed of the latent variables of the generated images: the same latent
# variables are used every time, so that the FID of a model does not change
# from one evaluation to the next.
SEED = 0


@torch.no_grad()
def evaluate(model):
    """Measure a trained VAE with the test images.

    FID: as many images as test images (5,000) are generated by decoding
    latent variables z drawn from the prior N(0, I). The FID is the Frechet
    distance between the Gaussian distributions fitted to the Inception-v3
    features of the generated images and of the test images. It is 0 when
    the two Gaussians are the same.

    Reconstruction error: every test image x is encoded and the mean mu of
    q(z|x) is decoded into x_hat (no sampling of z). The error of an image
    is the squared difference between x and x_hat, summed over the pixels;
    it is averaged over the test images.

    The model is not updated: it is put in evaluation mode and gradients are
    not tracked. The computation runs on the device of the model.

    Args:
        model: the trained VAE, with
                   latent_dim                 dimension of z
                   encode(x) -> (mu, logvar)  x of shape (B, 1, 32, 32)
                   decode(z) -> x_hat         shape (B, 1, 32, 32), values in [0, 1]

    Returns:
        dict {"fid": ..., "reconstruction_error": ...} of Python floats.
    """
    device = next(model.parameters()).device
    test_images = get_dataset("test").images
    model.eval()

    # latent variables of the generated images, one per test image
    generator = torch.Generator().manual_seed(SEED)
    z = torch.randn(len(test_images), model.latent_dim, generator=generator)

    fid = FrechetInceptionDistance(device=device)
    squared_error = 0.0

    for x, z_batch in zip(test_images.split(BATCH_SIZE), z.split(BATCH_SIZE)):
        x = x.to(device)

        # reconstruction of the test images
        mu, _ = model.encode(x)
        x_hat = model.decode(mu)
        squared_error += (x - x_hat).pow(2).sum().item()

        # generated images
        samples = model.decode(z_batch.to(device))
        if samples.shape != x.shape:
            raise ValueError(
                f"evaluate: model.decode returns images of shape {tuple(samples.shape)}, "
                f"expected {tuple(x.shape)}"
            )

        fid.update(_to_rgb(x), is_real=True)
        fid.update(_to_rgb(samples), is_real=False)

    return {
        "fid": fid.compute().item(),
        "reconstruction_error": squared_error / len(test_images),
    }


def save(result, info):
    """Save the result of `evaluate` in a CSV file.

    The file is result/result_<student ID>_<name>.csv. It has a header line
    and one line of values:

        student_id,name,fid,reconstruction_error

    Args:
        result: the dict returned by `evaluate`.
        info:   the dict returned by `get_info` in myinfo.py:
                {"name": ..., "student_id": ...}.

    Returns:
        the path of the saved file.
    """
    name = str(info["name"]).strip()
    student_id = str(info["student_id"]).strip()
    if not name or not student_id:
        raise ValueError("save: fill in your name and student ID in myinfo.py")

    RESULT_DIR.mkdir(parents=True, exist_ok=True)
    path = RESULT_DIR / f"result_{_for_filename(student_id)}_{_for_filename(name)}.csv"

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["student_id", "name", "fid", "reconstruction_error"])
        writer.writerow([student_id, name, result["fid"], result["reconstruction_error"]])

    return path


def _to_rgb(images):
    """Gray images (B, 1, H, W) -> RGB images (B, 3, H, W), float32 with
    values in [0, 1], as expected by the FID of torcheval."""
    return images.float().clamp(0, 1).repeat(1, 3, 1, 1)


def _for_filename(text):
    """Replace the characters that are not letters or digits (spaces, /, ...)
    by "_", so that the text can be part of a file name."""
    return "".join(c if c.isalnum() else "_" for c in text)
